    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String customer = (String) jComboBox1.getSelectedItem();
        String room = (String) jComboBox2.getSelectedItem();

        int customerId = Integer.parseInt(customer.split(" - ")[0]);
        int roomNo = Integer.parseInt(room);

        BookingDAO bookingDAO = new BookingDAO();
        RoomDAO roomDAO = new RoomDAO();

        boolean bookingSuccess = bookingDAO.allotRoom(customerId, roomNo);

        if (bookingSuccess) {

            roomDAO.updateRoomStatus(roomNo, "Occupied");

            JOptionPane.showMessageDialog(this,
                    "Room Allotted Successfully!");

            loadRooms();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Room Allotment Failed!");

        }
        
        loadCustomers();
        loadRooms();
        new DashboardUI().setVisible(true);

        dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

