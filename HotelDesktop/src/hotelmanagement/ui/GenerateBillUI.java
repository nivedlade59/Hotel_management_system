    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String room = (String) jComboBox2.getSelectedItem();

        if (room == null) {

            JOptionPane.showMessageDialog(this,
                    "No occupied room selected.");

            return;
        }

        int roomNo = Integer.parseInt(room);

        BookingDAO dao = new BookingDAO();

        currentBill = dao.getBillDetails(roomNo);

        if (currentBill != null) {

            jTextArea1.setText(
                "========== HOTEL BILL ==========\n\n"

                + "Customer Name : " + currentBill.getCustomerName()

                + "\nPhone         : " + currentBill.getPhone()

                + "\nAddress       : " + currentBill.getAddress()

                + "\n\n------------------------------"

                + "\nRoom Number   : " + currentBill.getRoomNo()

                + "\nDays Stayed   : " + currentBill.getDays()

                + "\nRate / Day    : $" + currentBill.getPrice()

                + "\n------------------------------"

                + "\nTOTAL BILL    : $" + currentBill.getTotal()

                + "\n\n=============================="
        );

        } else {

            JOptionPane.showMessageDialog(this,
                    "Bill could not be generated.");

        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (currentBill == null) {

            JOptionPane.showMessageDialog(this,
                    "Generate bill first.");

            return;
        }

        BookingDAO bookingDAO = new BookingDAO();

        RoomDAO roomDAO = new RoomDAO();

        boolean checkoutSuccess =
                bookingDAO.checkout(currentBill.getBookingId());

        if (checkoutSuccess) {

            roomDAO.updateRoomStatus(
                    currentBill.getRoomNo(),
                    "Available");

            JOptionPane.showMessageDialog(this,
                    "Checkout Successful.");

            jTextArea1.setText("");

            currentBill = null;

            loadOccupiedRooms();
            
            jComboBox2.setSelectedIndex(-1);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Checkout Failed.");

        }
        new DashboardUI().setVisible(true);

        dispose();
    }//GEN-LAST:event_jButton2ActionPerformed

