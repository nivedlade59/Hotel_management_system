    private void loadLogs() {

        ActivityLogDAO dao = new ActivityLogDAO();

        List<ActivityLog> logs = dao.getAllLogs();

        jTextArea1.setText("");

        if(logs.isEmpty()){

            jTextArea1.setText("No Login Activity Found.");

            return;
        }

        jTextArea1.append(
                "========== LOGIN HISTORY ==========\n\n");

        for(ActivityLog log : logs){

            jTextArea1.append(

                    "Log ID     : "
                    + log.getLogId()

                    + "\nUsername   : "
                    + log.getUsername()

                    + "\nLogin Time : "
                    + log.getLoginTime()

                    + "\n--------------------------------------\n\n"

            );

        }

    }

